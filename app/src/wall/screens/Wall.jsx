// deepest, so the masthead is one object: the fact, and the question.
function Ear({ letters }) {
  const err = wallError()
  const loaded = wallLoaded()
  let meta = null
  if (err) {
    meta = (
      <>
        <span className="wl-ear-meta">{err === 'offline' ? 'not connected here' : 'did not load'}</span>
        {err === 'offline' ? null : (
          <button type="button" className="wl-quiet wl-ear-again" onClick={() => loadWall(true)}>read it again</button>
        )}
      </>
    )
  } else if (letters > 0) {
    meta = (
      <span className="wl-ear-meta">
        <Roll value={letters} className="wl-ear-n" /> {letters === 1 ? 'letter' : 'letters'}
      </span>
    )
  } else if (loaded) {
    meta = <span className="wl-ear-meta">open now</span>
  }
  return (
    <div className="wl-ear" aria-live="polite">
      <span className="wl-ear-name">{campus().name}</span>
      {meta ? <span className="wl-ear-dot" aria-hidden="true">&middot;</span> : null}
      {meta}
    </div>
  )
}

// ── the search, on the wall ─────────────────────────────────────────────────
// Most people who scan the wall off a flyer are looking for one name, and
// usually their own. So the search is the wall's own question, and it stands
// where the eye lands after the veil goes: in the middle of the column,
// directly under the ear, with the bar over it.
//
// ── and it stands on something ──
// Twice it was type alone and twice nobody could find it. It was a 40px ring
// with a glass in it, in the corner of the bar a thumb reaches last, which
// read as settings; then it was a bare baseline at the left gutter, twenty-
